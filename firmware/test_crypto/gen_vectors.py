"""Writes vectors.h: real P-256 signatures (the iPhone's format: SHA-256, r|s) over login messages,
plus tampered copies, for verify_test.cpp. Run by CI before compiling the test."""

import os
import sys

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, utils


def c_bytes(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


rows = []
for i in range(20):
    key = ec.generate_private_key(ec.SECP256R1())
    n = key.public_key().public_numbers()
    pub = n.x.to_bytes(32, "big") + n.y.to_bytes(32, "big")
    msg = b"SLK3" + os.urandom(8) + os.urandom(16) + os.urandom(11)  # 39 bytes, like a v3 login
    r, s = utils.decode_dss_signature(key.sign(msg, ec.ECDSA(hashes.SHA256())))
    sig = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    rows.append((pub, msg, sig, 1))
    bad_msg = bytearray(msg)
    bad_msg[i % len(msg)] ^= 1 << (i % 8)  # one flipped bit in the message
    rows.append((pub, bytes(bad_msg), sig, 0))
    bad_sig = bytearray(sig)
    bad_sig[(i * 7) % 64] ^= 0x80  # one flipped bit in the signature
    rows.append((pub, msg, bytes(bad_sig), 0))

out = sys.argv[1] if len(sys.argv) > 1 else "vectors.h"
with open(out, "w") as f:
    f.write("// Generated by gen_vectors.py\n#include <cstdint>\n")
    f.write("struct Vector { uint8_t pub[64]; uint8_t msg[39]; uint8_t sig[64]; int valid; };\n")
    f.write("static const Vector kVectors[] = {\n")
    for pub, msg, sig, ok in rows:
        f.write(f"  {{{c_bytes(pub)}, {c_bytes(msg)}, {c_bytes(sig)}, {ok}}},\n")
    f.write("};\n")
print(f"wrote {len(rows)} vectors to {out}")
